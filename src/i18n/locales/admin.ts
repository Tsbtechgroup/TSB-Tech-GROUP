export type AdminCopyKey = keyof typeof adminCopy;
export type AdminLocaleCode = "fr" | "nl" | "en" | "de" | "es" | "it" | "pt" | "ar" | "tr" | "zh";

const ADMIN_LOCALES: readonly AdminLocaleCode[] = [
  "fr", "nl", "en", "de", "es", "it", "pt", "ar", "tr", "zh",
];

const buildAdminLocaleCopy = (locale: AdminLocaleCode) =>
  Object.fromEntries(
    Object.entries(adminCopy).map(([key, value]) => [
      key,
      value[locale],
    ])
  );

export const adminTranslations = Object.fromEntries(
  ADMIN_LOCALES.map((locale) => [
    locale,
    { admin: { copy: buildAdminLocaleCopy(locale) } },
  ])
) as unknown as TranslationResources;

const normalizeAdminSource = (value: string) =>
  value.replace(/\s+/g, " ").trim();

const adminSourceLookup = new Map<string, AdminCopyKey>();

Object.entries(adminCopy).forEach(([key, entry]) => {
  Object.values(entry).forEach((value) => {
    adminSourceLookup.set(
      normalizeAdminSource(value),
      key as AdminCopyKey
    );
  });
});

export const resolveAdminCopyKey = (value: string) =>
  adminSourceLookup.get(normalizeAdminSource(value));
